package app.fortem.tuning

/**
 * Правило расчёта сохраняется вместе с исполнением. Исправления живой настройки
 * не должны менять частоты записей, сделанных прежней версией приложения.
 */
enum class TuningModel {
    LEGACY_EQUAL_TONIC, // Формат 1: равномерная опора тоники и прежние таблицы.
    LEGACY_C4_TONIC,    // Формат 2: именованная опора от общей C4.
    TONIC_RELATIVE,     // Равномерная опора плюс энгармонический сдвиг.
}
